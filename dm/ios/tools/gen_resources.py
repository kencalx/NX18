#!/usr/bin/env python3
"""Save game resource paths and keep Xcode's derived data on the game's drive.

Called by build_ipa.sh after xcodegen. No game files are copied here.
Usage: gen_resources.py [--gen <dir>] [--no-workspace | --workspace-only] <ios> <RomFS> <marker> <shaders> <shader folder> <add-on content> <derived data> <dmsh_chain.h> [<pipeline archive> [<programs table>]]
  --gen: the folder resources.env and the derived data line of dm.xcconfig go in (default <ios>/Gen; build_ipa.sh's generation folder Gen/.stage, which becomes Gen/: the paths written
  name Gen/). --no-workspace leaves the project's workspace settings alone (build_ipa.sh writes the Gen files before xcodegen and the settings after it, --workspace-only)
"""
import getpass
import os
from pathlib import Path
import plistlib
import shlex
import sys


def workspace_settings(workspace, derived):
    settings = Path(workspace) / 'xcuserdata' / f'{os.environ.get("USER") or getpass.getuser()}.xcuserdatad/WorkspaceSettings.xcsettings'
    values = plistlib.loads(settings.read_bytes()) if settings.exists() else {}
    # A workspace-wide custom product path overrides the per-game target paths.
    # Keep only the cache preference here; the targets own their product/intermediate paths.
    values.update(BuildLocationStyle='UseAppPreferences', DerivedDataLocationStyle='AbsolutePath',
                  DerivedDataCustomLocation=str(Path(derived).resolve()))
    for key in ('CustomBuildLocationType', 'CustomBuildProductsPath', 'CustomBuildIntermediatesPath'):
        values.pop(key, None)
    data = plistlib.dumps(values)
    if settings.exists() and settings.read_bytes() == data: return   # unchanged: its times stay
    settings.parent.mkdir(parents=True, exist_ok=True)
    settings.write_bytes(data)


def main():
    args, gen, files, workspace = sys.argv[1:], None, True, True
    while args[:1] and args[0].startswith('--'):
        if args[0] == '--gen' and len(args) > 1: gen, args = args[1], args[2:]
        elif args[0] == '--no-workspace': workspace, args = False, args[1:]
        elif args[0] == '--workspace-only': files, args = False, args[1:]
        else: sys.exit(f'gen_resources.py: unknown option {args[0]}')
    ios, romfs, marker, shaders, msldir, aoc, derived, chain_h, *rest = args
    pso = rest[0] if rest else ''   # the pipeline archive made offline (build_ipa.sh, dm/gfx/tools/pso_offline.py), or none
    programs = rest[1:]   # a game of several programs: the table of each one's files (build_ipa.sh)
    ios = Path(ios)
    paths = {
        'DM_RESOURCE_ROMFS': str(Path(romfs).resolve()),
        'DM_RESOURCE_MARKER': marker,
        'DM_RESOURCE_SHADERS': str(Path(shaders).resolve()),
        'DM_RESOURCE_MSLDIR': msldir,
        'DM_RESOURCE_AOC': str(Path(aoc).resolve()) if aoc and Path(aoc).is_dir() else '',
        'DM_RESOURCE_CHAIN_H': str(Path(chain_h).resolve()),   # dm/gfx/nvn/dmsh_chain.h, which the host is compiled with (one chain version for every game)
        'DM_RESOURCE_PSO': str(Path(pso).resolve()) if pso and Path(pso).is_dir() else '',   # → <App>/pso, which the app hands the host as DM_PSO_BUNDLE
        # what the identity line of a RomFS image names (stage_resources.sh with DM_COPY_ROMFS=NO writes <App>/romfs.id): title ID, display version, package version
        'DM_RESOURCE_TITLE': os.environ.get('GAME', ''),
        'DM_RESOURCE_VERSION': os.environ.get('DM_APP_VERSION', ''),
        'DM_RESOURCE_BUILD': os.environ.get('DM_RESOURCE_BUILD', ''),
        'DM_RESOURCE_PROGRAMS': str(Path(ios, programs[0]).resolve()) if programs else '',   # with it, the RomFS and shaders above are program 0's and stage_resources.sh takes the table
    }
    gen = Path(gen) if gen else ios / 'Gen'
    if files:
        (gen / 'resources.env').write_text(
            '# Generated by build_ipa.sh; regenerate when the game or its drive changes.\n'
            + ''.join(f'{k}={shlex.quote(v)}\n' for k, v in paths.items()), encoding='utf-8')
        # Target build settings also pin products/intermediates here: command-line Xcode can
        # ignore the per-user workspace preference, and the app's resources are very large.
        with (gen / 'dm.xcconfig').open('a', encoding='utf-8') as config:
            config.write(f'DM_XCODE_OUTPUT_ROOT = {Path(derived).resolve()}\n')
    if workspace: workspace_settings(ios / 'DmIOS.xcodeproj/project.xcworkspace', derived)


if __name__ == '__main__':
    main()
