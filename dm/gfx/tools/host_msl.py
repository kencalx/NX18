#!/usr/bin/env python3
# The host's own Metal shaders (dm/gfx/msl/<name>.metal: clears, copies, the present, index conversions, geometry packing, ...), compiled when the host is built, so the host
# never compiles MSL source at run time. MTL4Compiler's newLibraryWithDescriptor: with a source compiles it through the MTLDevice (it calls newLibraryWithSource:), which
# the Metal performance HUD reports ("Compiled 2 shaders ... Consider adopting MTL4Compiler") and which held the submitting thread about 50 ms per library on an iPhone.
# Writes one C header (the host Makefile includes its directory; dm/gfx/nvn/host_msl.m reads it) with, per library, its name, its source (the fallback when the library
# is missing) and the metallib compiled for the SDK. Without the Metal toolchain the header has the sources only: the host then compiles them and says so in a [RED] line.
# Each run rechecks the compiler, SDK, deployment target and source contents. Matching inputs reuse the header without compiling; a toolchain installed after a source-only
# build regenerates the libraries. The header is written only when it changes, so an unchanged run does not rebuild the host.
# The header also holds the kernels of the start-up self-tests (DM_SELFTEST, dm/gfx/nvn/selftest.m: k_host_msl_chain, read through host_msl_chain_lib), which are compiled not
# as these libraries are but as the game chain compiles game shaders for the SDK (dm/gfx/tools/hmma_selftest.py), so a self-test measures what games get: one library a kernel
# (CHAIN_LIBS), each with its own record. A kernel that does not compile leaves the host without it ([RED] line) and the build goes on; the header's stamp then matches
# nothing, so the next build tries the kernel again.
# Usage: host_msl.py --sdk macosx|iphoneos [--min <OS version>] <header> <name.metal>...
import argparse, hashlib, os, subprocess, sys, tempfile

CHAIN_LIBS = ('hmma_selftest', 'hmma_selftest_flags')   # the self-test's libraries (hmma_selftest.LIBRARIES), by the names selftest.m asks for, each its entry even when left out

ap = argparse.ArgumentParser()
ap.add_argument('--sdk', required=True, choices=['macosx', 'iphoneos'])
ap.add_argument('--min', help='the lowest OS version the libraries must load on (iphoneos: the app\'s deployment target)')
ap.add_argument('out')
ap.add_argument('sources', nargs='+')
a = ap.parse_args()

def c_str(s):
    lines = s.split('\n')
    esc = lambda l: l.replace('\\', '\\\\').replace('"', '\\"')
    return '\n'.join(f'    "{esc(l)}\\n"' for l in lines[:-1]) + (f'\n    "{esc(lines[-1])}"' if lines[-1] else '') or '    ""'

ver = subprocess.run(['xcrun', '-sdk', a.sdk, 'metal', '--version'], capture_output=True, text=True)
ver = ver.stdout.splitlines()[0].strip() if ver.returncode == 0 and ver.stdout else ''
sdk = subprocess.run(['xcrun', '-sdk', a.sdk, '--show-sdk-path'], capture_output=True, text=True).stdout.strip()
sources = [(src, open(src).read()) for src in sorted(a.sources)]
selftest, chain_in, chain_why = None, '', ''
try:   # the self-test kernel: its source and its compile, from the chain's own files
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); import hmma_selftest
    selftest, chain_in = hmma_selftest, hmma_selftest.inputs(a.sdk)
except Exception as e:   # the host is built without it: a diagnostic never stops a build
    chain_why = f'its source could not be made ({type(e).__name__}: {e})'
# The generator itself is an input too: a changed compile flag or header format must invalidate an existing library.
inputs = hashlib.sha256(repr((a.sdk, a.min, ver, sdk, sources, chain_in, chain_why)).encode() + open(__file__, 'rb').read()).hexdigest()
stamp = f'// Inputs: {inputs}'
if os.path.exists(a.out):
    with open(a.out) as f:
        f.readline()
        if f.readline().rstrip('\n') == stamp: sys.exit(0)
if not ver: print(f'host_msl.py: no Metal compiler for {a.sdk} (xcodebuild -downloadComponent MetalToolchain): the host compiles its shaders at run time', file=sys.stderr)
out = ['// Generated by dm/gfx/tools/host_msl.py from dm/gfx/msl/*.metal: do not edit', stamp, f'#define HOST_MSL_SDK "{a.sdk}"', f'#define HOST_MSL_COMPILER "{ver or "none"}"']
ents = []
with tempfile.TemporaryDirectory() as td:
    for src, text in sources:
        name = os.path.splitext(os.path.basename(src))[0]
        lib = b''
        if ver:
            ml = os.path.join(td, name + '.metallib')
            cmd = ['xcrun', '-sdk', a.sdk, 'metal'] + ([f'-m{"ios" if a.sdk == "iphoneos" else "macosx"}-version-min={a.min}'] if a.min else []) + ['-o', ml, src]
            r = subprocess.run(cmd)
            if r.returncode: sys.exit(f'host_msl.py: {src} does not compile ({" ".join(cmd)})')
            lib = open(ml, 'rb').read()
        out.append(f'static const char k_host_msl_src_{name}[] =\n{c_str(text)};')
        out.append(f'static const unsigned char k_host_msl_lib_{name}[] = {{' + ','.join(str(b) for b in lib or b'\0') + '};')
        ents.append(f'    {{"{name}", k_host_msl_src_{name}, k_host_msl_lib_{name}, {len(lib)}}},')
    chain_ents = []
    for name in CHAIN_LIBS:
        array, chain_lib, record, why = 'k_host_msl_chain_' + name.replace('_selftest', ''), b'', '', chain_why
        if selftest and ver:
            try:
                path, record = selftest.build(a.sdk, td, name)
                with open(path, 'rb') as f: chain_lib = f.read()
            except Exception as e:   # a compile error, or anything else: the build goes on without it
                why = f'it did not compile when the host was built ({str(e).replace(td, "<build folder>")})'   # the same text for the same failure, so the header stays as it is
                out[1] = stamp + ' (the self-test kernel did not compile: tried again at the next build)'   # never matches: a failure from a passing cause (the compiler service, a full disk) is not kept
        if why: print(f'host_msl.py: [RED] the HMMA self-test kernel {name} for {a.sdk} is left out of the host: {why}', file=sys.stderr)
        elif not ver: why = f'no Metal compiler for {a.sdk} when the host was built'
        out.append(f'static const unsigned char {array}[] = {{' + ','.join(str(b) for b in chain_lib or b'\0') + '};')
        chain_ents.append(f'    {{"{name}", {c_str(why or record).strip()}, {array}, {len(chain_lib)}}},')   # record: the commands that compiled it, or why the build has none (lib_len 0)
out.append('static const struct { const char *name, *src; const unsigned char *lib; unsigned long lib_len; } k_host_msl[] = {\n' + '\n'.join(ents) + '\n};\n')
out.append('static const struct { const char *name, *record; const unsigned char *lib; unsigned long lib_len; } k_host_msl_chain[] = {\n' + '\n'.join(chain_ents) + '\n};\n')
text = '\n'.join(out)
if not os.path.exists(a.out) or open(a.out).read() != text:
    os.makedirs(os.path.dirname(a.out) or '.', exist_ok=True)
    with open(a.out + '.tmp', 'w') as f: f.write(text)
    os.replace(a.out + '.tmp', a.out)
print(f'host_msl.py: {len(ents)} libraries for {a.sdk}' + (f' ({ver})' if ver else ', sources only') + f' in {a.out}', file=sys.stderr)
