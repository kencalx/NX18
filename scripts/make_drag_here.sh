#!/bin/bash
# Makes "Drag Here.app", a droplet: drop a game's folder on it (its NSPs, and its mods folder and prod.keys if you have them) and Terminal opens and builds the game's IPA
# with scripts/drop_build.sh, for the iPhone unless you choose otherwise. Several folders dropped together are built one after another in one Terminal window (each build
# sizes itself to the whole Mac, and the app build step is one per checkout); a build that stops leaves its lines there and the next one starts. Double-click it to pick a
# folder instead. It runs the build from this checkout, so pulling the repository updates it too.
# Usage: scripts/make_drag_here.sh [iphone | ipad | both] [<where to put the app>]   (defaults: iphone, the Desktop)
# The first drop asks to let it control Terminal (System Settings > Privacy & Security > Automation); allow it.
set -eu
repo=$(cd "$(dirname "$0")/.." && pwd)
device=${1:-iphone}; out=${2:-$HOME/Desktop}
case $device in iphone | ipad | both) ;; *) echo "usage: $0 [iphone | ipad | both] [<folder>]" >&2; exit 1;; esac
case $device in iphone) name="Drag Here";; ipad) name="Drag Here (iPad)";; both) name="Drag Here (iPhone + iPad)";; esac
app="$out/$name.app"
chmod +x "$repo/scripts/drop_build.sh"
bs=$(printf '%s' "$repo/scripts/drop_build.sh" | sed 's/[\\"]/\\&/g')   # as an AppleScript string: \ and " escaped
tmp=$(mktemp -d "${TMPDIR:-/tmp}/dragherescpt.XXXXXX"); trap 'rm -rf "$tmp"' EXIT
src=$tmp/drag.applescript
cat > "$src" <<APPLESCRIPT
-- Generated by scripts/make_drag_here.sh: the dropped folders are built one after another in one Terminal window (scripts/drop_build.sh, device $device)
property buildScript : "$bs"
property targetDevice : "$device"

on open droppedItems
	set theCommand to ""
	set n to count of droppedItems
	repeat with i from 1 to n
		set theCommand to theCommand & (my buildCommand(POSIX path of (item i of droppedItems)))
		-- every build but the last reads no keyboard, so it does not wait at its "Press Return" line before the next one
		if i < n then set theCommand to theCommand & " </dev/null ; "
	end repeat
	my runInTerminal(theCommand)
end open

on run
	set chosen to choose folder with prompt "Choose the folder that holds the game's NSPs:"
	my runInTerminal(my buildCommand(POSIX path of chosen))
end run

on buildCommand(folderPath)
	return (quoted form of buildScript) & " " & (quoted form of folderPath) & " " & targetDevice
end buildCommand

on runInTerminal(theCommand)
	tell application "Terminal"
		activate
		do script theCommand
	end tell
end runInTerminal
APPLESCRIPT
rm -rf "$app"
osacompile -o "$app" "$src"
echo "made: $app"
echo "Drop a game's folder on it. The first time, allow it to control Terminal."
